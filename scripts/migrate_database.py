INDEXES = (
    "CREATE INDEX idx_exercises_equipment ON public.dim_exercises(equipment)",
    "CREATE INDEX idx_exercises_pattern ON public.dim_exercises(pattern)",
    "CREATE INDEX idx_exercises_primary_muscle ON public.dim_exercises(primary_muscle)",
    "CREATE INDEX idx_fact_exercise_history ON public.fact_workout_sets(user_id, exercise_id, created_at)",
    "CREATE INDEX idx_fact_routine_template ON public.fact_workout_sets(routine_id, training_id)",
    "CREATE INDEX idx_fact_user_training ON public.fact_workout_sets(user_id, training_id)",
)


def validate_source(source: sqlite3.Connection) -> dict[str, int]:
    tables = {
        row[0] for row in source.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
        )
    }
    if tables != set(TABLES):
        raise ValueError("SQLite tables differ from the supported four-table schema; update the migration first.")
    if source.execute("PRAGMA integrity_check").fetchall() != [("ok",)]:
        raise ValueError("SQLite integrity check failed; repair the source before migrating.")
    if source.execute("PRAGMA foreign_key_check").fetchone() is not None:
        raise ValueError("SQLite contains foreign-key violations; repair the source before migrating.")
    return {
        table: source.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0]
        for table in TABLES
    }


def connection_uri() -> str:
    uri = os.environ.get("DATABASE_URL", "").strip()
    if not uri:
        gcloud = shutil.which("gcloud")
        if gcloud is None:
            raise ValueError("Set DATABASE_URL or install gcloud and authenticate with gcloud auth login.")
        result = subprocess.run(
            [
                gcloud, "secrets", "versions", "access", "latest",
                "--secret=orchestratorapp-prod-database-url", "--project=basicrahgapp",
            ],
            capture_output=True, text=True, check=False,
        )
        if result.returncode != 0:
            raise ValueError("Cannot read the database secret. Check gcloud login and secret accessor permissions.")
        uri = result.stdout.strip()
    try:
        parsed = urlsplit(uri)
        options = parse_qs(parsed.query)
        valid = (
            parsed.scheme in ("postgres", "postgresql") and parsed.hostname
            and parsed.username and parsed.password and parsed.path not in ("", "/")
            and options.get("sslmode") in (["require"], ["verify-ca"], ["verify-full"])
        )
    except ValueError:
        valid = False
    if not valid:
        raise ValueError("DATABASE_URL must be a PostgreSQL URI with database credentials and sslmode=require or stronger.")
    return uri


def populate(source: sqlite3.Connection, target: psycopg.Connection) -> dict[str, int]:
    """Create and verify the import inside a transaction owned by the caller."""
    counts = validate_source(source)
    with target.cursor() as cursor:
        cursor.execute("SELECT pg_advisory_xact_lock(724183970315)")
        cursor.execute(
            "SELECT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f'))"
        )
        if cursor.fetchone()[0]:
            raise ValueError("Destination public schema is not empty. No existing tables or data will be overwritten.")

        for table, statement in TABLES.items():
            cursor.execute(statement)
            columns = [
                row[1] for row in source.execute(f'PRAGMA table_info("{table}")')
            ]
            selection = sql.SQL("SELECT {} FROM {} ORDER BY id").format(
                sql.SQL(", ").join(map(sql.Identifier, columns)),
                sql.Identifier("public", table),
            )
            cursor.execute(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = 'public' AND table_name = %s ORDER BY ordinal_position",
                (table,),
            )
            if [row[0] for row in cursor.fetchall()] != columns:
                raise ValueError(f"SQLite columns differ from the supported schema for {table}.")

            rows = source.execute(f'SELECT * FROM "{table}" ORDER BY id')
            with cursor.copy(
                sql.SQL("COPY {} ({}) FROM STDIN").format(
                    sql.Identifier("public", table),
                    sql.SQL(", ").join(map(sql.Identifier, columns)),
                )
            ) as transfer:
                while batch := rows.fetchmany(BATCH_SIZE):
                    for row in batch:
                        transfer.write_row(row)

            cursor.execute(selection)
            original = source.execute(f'SELECT * FROM "{table}" ORDER BY id')
            while True:
                expected = original.fetchmany(BATCH_SIZE)
                actual = cursor.fetchmany(BATCH_SIZE)
                if expected != actual:
                    raise ValueError(f"Row verification failed for {table}; the import will be rolled back.")
                if not expected:
                    break

            maximum = source.execute(f'SELECT MAX(id) FROM "{table}"').fetchone()[0] or 0
            sequence = source.execute(
                "SELECT seq FROM sqlite_sequence WHERE name = ?", (table,)
            ).fetchone()
            high_water = max(maximum, sequence[0] if sequence else 0)
            cursor.execute(
                "SELECT setval(pg_get_serial_sequence(%s, 'id'), %s, %s)",
                (f"public.{table}", max(1, high_water), high_water > 0),
            )

        for statement in INDEXES:
            cursor.execute(statement)
    return counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE_DATABASE, help="SQLite source file (default: database/gym_app.db).")
    parser.add_argument("--dry-run", action="store_true", help="Check SQLite and show counts without connecting to Neon.")
    args = parser.parse_args(argv)
    path = args.source.resolve()
    if not path.is_file():
        parser.error(f"SQLite source does not exist: {path}")
    try:
        with closing(sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)) as source:
            source.execute("PRAGMA query_only = ON")
            source.execute("BEGIN")
            counts = validate_source(source)
            if args.dry_run:
                print("Source checks passed. No PostgreSQL connection or writes performed.")
            else:
                uri = connection_uri()
                with psycopg.connect(uri, connect_timeout=30, application_name="orchestrator-db-migration") as target:
                    with target.transaction():
                        counts = populate(source, target)
                print("Import committed; all copied rows verified.")
            for table, count in counts.items():
                print(f"{table}: {count} rows")
        return 0
    except psycopg.Error as error:
        code = error.sqlstate or "connection/client error"
        print(f"PostgreSQL migration failed ({code}). Import was not committed. Check connectivity, permissions, and schema constraints.", file=sys.stderr)
        return 1
    except (sqlite3.Error, ValueError, OSError) as error:
        print(f"Migration failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())